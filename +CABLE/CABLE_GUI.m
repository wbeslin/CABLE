    % pushbuttonRunAbort_Callback .........................................
    function pushbuttonRunAbort_Callback(src,edata)
        try
            switch src.String
                case 'Run'
                    % check runnability
                    [runnable,runnableErrMsg] = inParams.isRunnable();
                    if ~runnable
                        warndlg(runnableErrMsg,'Warning: Cannot Run','modal')
                        return
                    end
                    
                    % validate input and output paths, if input is a folder
                    inputPath = uihandles.main.editInputPath.String;
                    outputPath = uihandles.main.editOutputPath.String;
                    if isdir(inputPath)
                        % make sure input and output are seperate
                        iInOutCommon = strfind(outputPath,inputPath);
                        if ~isempty(iInOutCommon) && iInOutCommon(1) == 1
                            warnMsg = sprintf('Output is set to be saved inside the input directory.\nInput and output should be kept seperate.');
                            warndlg(warnMsg,'Warning: Cannot Run','modal')
                            return
                        end
                    end
                    
                    % create output folder
                    [outputDirPath,outDirCreated,outErrMsg] = createOutputDir(outputPath,inputPath);
                    if ~outDirCreated
                        warnMsg = sprintf('Unable to save output:\n%s',outErrMsg);
                        warndlg(warnMsg,'Warning: Cannot Run','modal')
                        return
                    end

                    % get length equations from listbox
                    if ~isempty(lengthEquations)
                        selectedLengthEquations = lengthEquations(uihandles.main.listboxLengthEquations.Value,:);
                    else
                        selectedLengthEquations = lengthEquations;
                    end
                    
                    % run
                    run(inputPath,outputDirPath,inParams,selectedLengthEquations,classFile,stateManagers,uihandles.main.pushbuttonRunAbort,monitor,plotter)
                    if kill
                        delete(uihandles.win.fig)
                    end
                case 'Abort'
                    % abort
                    monitor.abort = true;
                otherwise
                    error('Unrecognized state')
            end
        catch ME
            fatalError(uihandles.win.fig,ME)
        end
    end

