    % pushbuttonLoad_Callback .............................................
    function pushbuttonLoad_Callback(src,edata)
        try 
            dataDir = uigetdir(inParams.getValue('outputPath'));
            if isnumeric(dataDir)
                return
            end
            
            [~,dataDirName] = fileparts(dataDir);
            if ischar(dataDir)
                % get directory contents
                fNames = getDirContents(dataDir);
                
                % search for a filtered IPI file
                lIPIFile = strcmp('FilteredIPIs.csv',fNames);
                if ~any(lIPIFile)
                    warndlg('Filtered IPI file not found','Warning','modal')
                    return
                end
                IPIFileName = fNames{lIPIFile};
                IPIFilePath = fullfile(dataDir,IPIFileName);
                IPITable = readtable(IPIFilePath);
                IPIs = IPITable.IPI;
                
                % make sure there are IPIs
                if isempty(IPIs)
                    warndlg('No IPIs to plot!','Warning','modal')
                    return
                end
                
                % search for GMM DeltaBIC file
                lDBICFile = strcmp('GMM_DeltaBICs.csv',fNames);
                if any(lDBICFile)
                    DBICFileName = fNames{lDBICFile};
                    DBICFilePath = fullfile(dataDir,DBICFileName);
                    DBICTable = readtable(DBICFilePath);
                    DeltaBICs = table2array(DBICTable)';

                    % search for GMM files
                    nGMMs = numel(DeltaBICs);
                    GMMTables = cell(nGMMs,1);
                    for ii = 1:nGMMs
                        lGMMFileii = strcmp(sprintf('GMM%d.csv',ii),fNames);
                        if sum(lGMMFileii) ~= 1
                            warndlg('Could not find all GMM files','Warning','modal')
                            return
                        end
                        GMMFileNameii = fNames{lGMMFileii};
                        GMMFilePathii = fullfile(dataDir,GMMFileNameii);
                        GMMTables{ii} = readtable(GMMFilePathii);
                    end
                else
                    DeltaBICs = double.empty(0,1);
                    GMMTables = cell.empty(0,1);
                end
                
                % plot data
                Fs = 48000;
                showPlot = true;
                plotter.setData(dataDirName,dataDir,IPIs,GMMTables,DeltaBICs,Fs,inParams.getValue('IPIRange'),showPlot)
            end
        catch ME
            fatalError(uihandles.win.fig,ME)
        end
    end

