%% createStateManager -----------------------------------------------------
function stateManagers = createStateManagers(uihandles)
% Creates UIStateManager objects to manage the on/off status of UI
% components.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % I/O
    hI = [uihandles.main.panelInput;getDecendents(uihandles.main.panelInput)];
    hO = [uihandles.main.panelOutput;getDecendents(uihandles.main.panelOutput)];
    stateManager_IO = CABLE.UIManagement.UIStateManager([hI;hO]);

    % plotting
    hPlotting = [uihandles.plotting.tab;getDecendents(uihandles.plotting.tab)];
    stateManager_plotting = CABLE.UIManagement.UIStateManager(hPlotting);
    
    % advanced
    hAdvanced = [uihandles.advanced.tab;getDecendents(uihandles.advanced.tab)];
    stateManager_advanced = CABLE.UIManagement.UIStateManager(hAdvanced);
    
    % put everything together in a struct
    stateManagers = struct(...
        'IO',stateManager_IO,...
        'plotting',stateManager_plotting,...
        'advanced',stateManager_advanced);
    
    % NESTED FUNCTIONS
    % getDecendents .......................................................
    function d = getDecendents(p)
    % Returns the children of an object, and all of their children.
    % The function achieves recursion by calling itself.
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    
        % get immediate children of parent
        c = p.Children;
        d = c;

        % add children of children
        nc = numel(c);
        for iin = 1:nc
            cii = c(iin);

            % check if child has children, and add them if it does
            if isprop(cii,'Children')
                dii = getDecendents(cii);
                d = [d;dii]; % ignore warning
            end
        end
    end
end

