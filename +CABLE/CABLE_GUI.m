    % initialize variables based on state
    switch state
        case 'idle'
            uiState = 'on';
            string_RunAbort = 'Run';
            colour_RunAbort = [0 205 0]/255;
        case 'running'
            uiState = 'off';
            string_RunAbort = 'Abort';
            colour_RunAbort = [235 55 55]/255;
        otherwise
            error('Unrecognized state')
    end
    
    % activate or deactivate UI components
    stateManagers.IO.toggleState(uiState);
    stateManagers.plotting.toggleState(uiState);
    stateManagers.advanced.toggleState(uiState);
    
    % change appearance of Run/Abort button
    h_pushbuttonRunAbort.String = string_RunAbort;
    h_pushbuttonRunAbort.BackgroundColor = colour_RunAbort;
end

%% run --------------------------------------------------------------------
function run(inputPathMaster,outputPathMaster,inParams,lengthEquations,classFile,stateManagers,h_pushbuttonRunAbort,monitor,plotter)
% Initializes and runs the IPI compilation routine
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

    % set running state
    setupProgramState('running',stateManagers,h_pushbuttonRunAbort);
    
    try
        % initialize monitor
        monitor.totalReset()
        monitor.setMessage('Initializing')

        % set debug output option
        doDebug = false;
        
        % get output options from inParams
        saveAllIPIs = inParams.getValue('saveData_AllIPIs');
        saveFilteredIPIs = inParams.getValue('saveData_FilteredIPIs');
        saveClusters = inParams.getValue('saveData_Clusters');
        displayPlots = inParams.getValue('displayPlots');
        savePlots = inParams.getValue('savePlots');
        
        % process plotting options
        doPlot = displayPlots || ~strcmp(savePlots,'None');
        if doPlot || saveFilteredIPIs || saveClusters
            doFilteredIPIs = true;
            doClusters = true;
            if displayPlots
                showPlots = true;
            else
                showPlots = false;
            end
            showPlotWaitBar = false;
            plottingFs = 48000;
            plottingIPIRange = inParams.getValue('IPIRange');
        else
            doFilteredIPIs = false;
            doClusters = false;
        end
        
        % process All IPIs option
        if saveAllIPIs
            doAllIPIs = true;
        else
            doAllIPIs = false;
        end
        
        % create IPI method and Chi Square input structs
        doIPIMethod = struct(...
            'Autocorrelation',inParams.getValue('doIPIMethod_Autocorrelation'),...
            'Cepstrum',inParams.getValue('doIPIMethod_Cepstrum'));
        useChiSquared = struct(...
            'Autocorrelation',inParams.getValue('useChiSquared_Autocorrelation'),...
            'Cepstrum',inParams.getValue('useChiSquared_Cepstrum'));

        % open parallel pool
        nCores = inParams.getValue('nCores');
        p = gcp('nocreate');
        if nCores > 1
            if isempty(p)
                % create pool
                parpool(nCores);
            elseif p.NumWorkers ~= nCores
                % reset pool
                delete(gcp)
                parpool(nCores);
            end
        elseif ~isempty(p)
            % shut down pool
            delete(gcp)
        end

        % get file-specific input and output paths, and their durations
        [inputPaths,outputPaths] = createIOPaths(inputPathMaster,outputPathMaster);
        fileDurations = getFileDurations(inputPaths);
        nFiles = numel(inputPaths);

        % update monitor
        monitor.setFileCount(nFiles)
        monitor.setFileDurations(fileDurations);
        monitor.startTimer()

        % loop through each file and run IPI compiler
        for ii = 1:nFiles
            monitor.newFile()
            inputPathii = inputPaths{ii};
            outputPathii = outputPaths{ii};
            [~,fileNameii,fileExtii] = fileparts(inputPathii);
            monitor.setFileName([fileNameii,fileExtii])
            if doClusters
                clusterMsgii = '';
            else
                clusterMsgii = 'None';
            end

            % if file is a directory, get list of files
            if isdir(inputPathii)
                inputii = getDirContents(inputPathii);
                inputii = strcat(...
                    repelem({inputPathii},numel(inputii),1),...
                    repelem({filesep},numel(inputii),1),...
                    inputii);
            else
                inputii = {inputPathii};
            end

            % process file
            try 
                % Run IPI compilation
                IPIData = CABLE.Routine.main(...
                    'inputFiles',inputii,...
                    'monitor',monitor,...
                    'classFile',classFile,...
                    'doDebug',doDebug,...
                    'doAllIPIs',doAllIPIs,...
                    'doFilteredIPIs',doFilteredIPIs,...
                    'doClusters',doClusters,...
                    'nIPIReps',inParams.getValue('nIPIReps'),...
                    'minGoodProb',inParams.getValue('minGoodProb'),...
                    'recSplitDuration',inParams.getValue('recSplitDuration'),...
                    'minSegmentDuration',inParams.getValue('minSegmentDuration'),...
                    'channelIndex',inParams.getValue('channelIndex'),...
                    'threshOn',inParams.getValue('threshOn'),...
                    'threshOff',inParams.getValue('threshOff'),...
                    'alphaSignal',inParams.getValue('alphaSignal'),...
                    'alphaNoiseOn',inParams.getValue('alphaNoiseOn'),...
                    'alphaNoiseOff',inParams.getValue('alphaNoiseOff'),...
                    'minEchoProp',inParams.getValue('minEchoProp'),...
                    'IPIRange',inParams.getValue('IPIRange'),...
                    'maxClickDuration',inParams.getValue('maxClickDuration'),...
                    'minClickSep',inParams.getValue('minClickSep'),...
                    'tukeyFalloffDuration',inParams.getValue('tukeyFalloffDuration'),...
                    'pulseDurationRange',inParams.getValue('pulseDurationRange'),...
                    'smoothBandwidths',inParams.getValue('smoothBandwidths'),...
                    'nSmoothRuns',inParams.getValue('nSmoothRuns'),...
                    'peakBaseHeightProp',inParams.getValue('peakBaseHeightProp'),...
                    'promThreshProp',inParams.getValue('promThreshProp'),...
                    'minPromThreshScale',inParams.getValue('minPromThreshScale'),...
                    'maxIPIDeviation',inParams.getValue('maxIPIDeviation'),...
                    'doIPIMethod',doIPIMethod,...
                    'useChiSquared',useChiSquared,...
                    'ICIRange',inParams.getValue('ICIRange'),...
                    'ICITol',inParams.getValue('ICITol'),...
                    'IPITol',inParams.getValue('IPITol'),...
                    'KDEBandwidths',inParams.getValue('KDEBandwidths'),...
                    'nkExtra',inParams.getValue('nkExtra'),...
                    'shareSigma',inParams.getValue('shareSigma'),...
                    'sigma2RegVal',inParams.getValue('sigma2RegVal'),...
                    'EMTol',inParams.getValue('EMTol'),...
                    'maxEMIterations',inParams.getValue('maxEMIterations'),...
                    'maxEMTries',inParams.getValue('maxEMTries'));

                % save output
                if ~isdir(outputPathii)
                    mkdir(outputPathii)
                end
                %%% all IPIs
                if saveAllIPIs
                    writetable(IPIData.AllIPIs,fullfile(outputPathii,'AllIPIs.csv'))
                end
                %%% filtered IPIs
                if saveFilteredIPIs
                    writetable(IPIData.FilteredIPIs,fullfile(outputPathii,'FilteredIPIs.csv'))
                end
                %%% clusters and length estimation
                if doClusters
                    clusterMsgii = IPIData.Clusters.message;
                    nGMMsii = numel(IPIData.Clusters.GMMs);
                    GMMTablesii = cell(nGMMsii,1);
                    if nGMMsii > 0
                        % create cell arrays of names for GMMs and length
                        % equations
                        GMMNames = strcat('GMM',strsplit(num2str(1:nGMMsii)));
                        EQNames = strcat('Length_',lengthEquations.Name)';
                        nEQ = numel(EQNames);

                        % save DeltaBICs
                        if saveClusters
                            DeltaBICTable = array2table(round(IPIData.Clusters.deltaBICs,3),'VariableNames',GMMNames);
                            writetable(DeltaBICTable,fullfile(outputPathii,'GMM_DeltaBICs.csv'))
                        end

                        % save info on individual models
                        for jj = 1:nGMMsii
                            %%% Extract cluster info
                            GMMNamejj = GMMNames{jj};
                            GMMjj = IPIData.Clusters.GMMs{jj};
                            nClustersjj = numel(GMMjj.mu);
                            mujj = reshape(GMMjj.mu,nClustersjj,1);
                            if inParams.getValue('shareSigma')
                                sigmajj = repelem(sqrt(GMMjj.Sigma),nClustersjj,1);
                            else
                                sigmajj = reshape(sqrt(GMMjj.Sigma),nClustersjj,1);
                            end
                            pjj = reshape(GMMjj.ComponentProportion,nClustersjj,1);

                            %%% compute body lengths from mu
                            bodyLengthsjj = cell(1,nEQ);
                            for kk = 1:nEQ
                                bodyLengthsjj{kk} = round(polyval(lengthEquations.Coefficients{kk},mujj),2);
                            end

                            %%% save table
                            GMMTablejj = table(...
                                round(mujj,3),...
                                round(sigmajj,3),...
                                round(pjj,3),...
                                bodyLengthsjj{:},...
                                'VariableNames',[{'mu','sigma','p'},EQNames]);
                            if saveClusters
                                writetable(GMMTablejj,fullfile(outputPathii,[GMMNamejj,'.csv']))
                            end
                            GMMTablesii{jj} = GMMTablejj;
                        end
                    end
                    
                    % display and/or save figures if specified
                    plottingIPIsii = IPIData.FilteredIPIs.IPI;
                    if doPlot && ~isempty(plottingIPIsii)
                        monitor.setMessage('Creating plots')
                        plottingGMMsii = GMMTablesii;
                        plottingDeltaBICsii = IPIData.Clusters.deltaBICs;
                        %plotNumsii = (1:(numel(plottingGMMsii)+1))';
                        plotter.setData(fileNameii,outputPathii,plottingIPIsii,plottingGMMsii,plottingDeltaBICsii,plottingFs,plottingIPIRange,showPlots)
                        nPlotsii = nGMMsii + 1;
                        switch savePlots
                            case 'None'
                                iPlotSaveii = double.empty(0,1);
                            case 'Distribution Only'
                                iPlotSaveii = 1;
                            case 'Best Model'
                                iPlotSaveii = 2;
                            case 'Best Model + Distribution'
                                iPlotSaveii = [1;2];
                            case 'All Models'
                                iPlotSaveii = (2:nPlotsii)';
                            case 'All Models + Distribution'
                                iPlotSaveii = (1:nPlotsii)';
                            otherwise
                                error('Encountered bug: unrecognized plot saving option')
                        end
                        iPlotSaveii = iPlotSaveii(iPlotSaveii <= nPlotsii);
                        if ~isempty(iPlotSaveii)
                            plotter.saveFig(outputPathii,iPlotSaveii,showPlotWaitBar);
                        end
                        if ~displayPlots
                            plotter.closeFig;
                        end
                    end
                end
                
                % mark success
                successii = true;
                statusMsgii = 'Succeeded';
            catch ME
                successii = false;
                if monitor.abort
                    statusMsgii = 'Aborted';
                else
                    %statusMsgii = sprintf('Failed at step: %s\nCause: %s',monitor.messageStr,ME.message);
                    if strcmp(ME.identifier,'CABLE:Routine:main:BadInput')
                        failCause = ME.message;
                    else
                        failCause = ME.getReport('extended','hyperlinks','off');
                    end
                    statusMsgii = sprintf('Failed at step:\n"%s"\n\nCause:\n%s',monitor.messageStr,failCause);
                    clear failCause
                end
            end

            % create log file
            createLogFile(statusMsgii,clusterMsgii,monitor,inParams,outputPathii)

            % mark end of file
            if monitor.abort
                rethrow(ME)
            else
                monitor.endFile(successii)
            end
        end
    catch ME
        if ~monitor.abort
            rethrow(ME)
        end
    end
    
    % return to idle state
    setupProgramState('idle',stateManagers,h_pushbuttonRunAbort);
    
    % signal end of run
    if monitor.abort
        monitor.abort = false;
        monitor.setMessage('Aborted')
        %msgbox('Run aborted','modal')
    else
        msgbox('Run complete!','modal')
    end
    
    % NESTED FUNCTIONS
    % createIOPaths .......................................................
    function [inputPaths,outputPaths] = createIOPaths(inputPathMaster,outputPathMaster)
    % Creates cell arrays of full input and output paths.
    % If the master input path points to a file, then there is only one 
    % input and output. The returned paths are the same as the master 
    % paths. But if the master input path points to a directory, then there
    % are multiple input and output paths, one for each file within. In
    % this case, the output paths add a folder within the master output
    % folder.
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    
        if isdir(inputPathMaster)
            % get list of input files
            inputFiles = getDirContents(inputPathMaster);
            nInputFiles = numel(inputFiles);

            % create list of file-specific input and output paths
            inputPaths = cell(nInputFiles,1);
            outputPaths = cell(nInputFiles,1);
            for iin = 1:nInputFiles
                % initialize loop variables
                fileiin = inputFiles{iin};
                [~,fileNameiin] = fileparts(fileiin);

                % input
                inputPaths{iin} = fullfile(inputPathMaster,fileiin);

                % output
                outputPaths{iin} = fullfile(outputPathMaster,fileNameiin);
            end
        else
            inputPaths = {inputPathMaster};
            outputPaths = {outputPathMaster};
        end
    end
    
    % getFileDurations ....................................................
    function d = getFileDurations(inputPaths)
    % Retrieve duration of every file. For directory inputs, all files are
    % pooled.
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    
        nInputs = numel(inputPaths);
        d = duration(zeros(nInputs,3));
        for iin = 1:nInputs
            try
                inputiin = inputPaths{iin};
                if isdir(inputiin)
                    inputContentsiin = getDirContents(inputiin);
                    nFilesiin = numel(inputContentsiin);
                    diin = duration(zeros(nFilesiin,3));
                    for jjn = 1:nFilesiin
                        filejjn = fullfile(inputiin,inputContentsiin{jjn});
                        fileInfojjn = audioinfo(filejjn);
                        diin(jjn) = duration(0,0,fileInfojjn.Duration);
                    end
                    d(iin) = sum(diin);
                else
                    fileiin = inputPaths{iin};
                    fileInfoiin = audioinfo(fileiin);
                    d(iin) = duration(0,0,fileInfoiin.Duration);
                end
            catch
                % non-audio file: duration is 0
            end
        end
    end

    % createLogFile .......................................................
    function createLogFile(statusMsg,clusterMsg,monitor,inParams,outputPath)
    % Creates a text file recording information about a file run.
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%    
    
        % create log strings
        statusHead = 'COMPLETION STATUS';
        statusStr = sprintf('%s\n%s\n%s',statusHead,repelem('-',numel(statusHead)),statusMsg);
        clusterHead = 'CLUSTERING';
        clusterStr = sprintf('%s\n%s\n%s',clusterHead,repelem('-',numel(clusterHead)),clusterMsg);
        fileInfoHead = 'FILE INFO';
        fileInfoStr = sprintf('%s\n%s\n%s',fileInfoHead,repelem('-',numel(fileInfoHead)),monitor.getFormattedFileInfo);
        paramHead = 'INPUT PARAMETERS';
        paramStr = sprintf('%s\n%s\n%s',paramHead,repelem('-',numel(paramHead)),inParams.getFormattedList);
        
        % open a file for writing
        if ~isdir(outputPath)
            mkdir(outputPath)
        end
        [fID,fErr] = fopen(fullfile(outputPath,'log.txt'), 'w');
        if fID > 0
            try
                % print to file
                fprintf(fID,'%s\n\n\n%s\n\n\n%s\n\n\n%s',statusStr,clusterStr,fileInfoStr,paramStr);
            catch MEn
                warning('Failed to print to file:\n%s',MEn.message)
            end

            % close file
             fclose(fID);
        else
            warning('Could not create log file:\n%s',fErr)
        end
    end
end

%% createOutputDir --------------------------------------------------------
function [outPath,creationSucceeded,errMsg] = createOutputDir(parentPath,inputPath)
% Creates an output directory inside a parent path. 
% This directory is given an automatic name, succeeded by a numeric suffix.
% The suffix value depends on the number of already-existing outputs that
% have the same name.
% This approach avoids having to deal with already-full directories.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% NOTE: inside the run callback, make sure input and output are not the
% same. Just issue a warning and abort.

    % initialize variables
    outNameAppend = '_IPIData';
    [~,inFileName] = fileparts(inputPath);
    outNameBase = [inFileName,outNameAppend];
    %%% define regular expression to extract numeric appendices of any
    %%% existing output folders
    outNumRegex = ['(?<=(^',outNameBase,'))\d*$'];
    
    % search parent directory for existing output files
    dirContents = dir(parentPath);
    dirContents = {dirContents.name}';
    
    % get numeric appendices of existing outputs
    regexMatch = regexp(dirContents,outNumRegex,'match');
    numExistCellStr = [regexMatch{:}];
    numExist = cellfun(@str2double,numExistCellStr);
    
    % find an unused number
    if isempty(numExist)
        numAppend = 1;
    else
        numArray = 1:max(numExist)+1;
        numUnused = setdiff(numArray,numExist);
        numAppend = numUnused(1);
    end
    
    % create directory
    outName = [outNameBase,num2str(numAppend)];
    outPath = fullfile(parentPath,outName);
    [creationSucceeded,errMsg] = mkdir(outPath);
end

%% getDirContents ---------------------------------------------------------
function fNames = getDirContents(dirPath)
% Returns the names of all files in a folder as a cellstr.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

    % define regular expression to find strings that are only a series 
    % of dots. These always appear when scanning directories and are
    % not of interest.
    badFileRegex = '^\.*$';

    % get directory structure
    dirContents = dir(dirPath);
    fNames = {dirContents.name}';
    regexMatch = regexp(fNames,badFileRegex);
    goodFiles = cellfun('isempty',regexMatch);
    fNames = fNames(goodFiles);
end

%% fatalError -------------------------------------------------------------
function fatalError(hFig,ME)
% Call this function if an unexpected error was encountered.
% Will notify the user, create a crash dump, and close the program.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

    % create crash dump
    try
        crashFile = writeCrashDump(ME);
        msgAppend = sprintf('Error details have been written to:\n"%s".\n\nPlease send this file to the developer at "wilfried.beslin@dal.ca".',crashFile);
    catch ME2
        msgAppend = sprintf('Error details could not be saved. Reason given was:\n"%s".\n\nPlease notify the developer at "wilfried.beslin@dal.ca".',ME2.message);
    end
    
    % notify user
    msg = sprintf('CABLE encountered an internal error and needs to close.\n\n%s',msgAppend);
    hErr = errordlg(msg,'Fatal Error','modal');
    waitfor(hErr)
    
    % close program
    delete(hFig);
end

%% writeCrashDump ---------------------------------------------------------
function crashFile = writeCrashDump(ME)
% Writes fatal error message to a text file
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

    % create file name based on current date and time
    t0 = datetime();
    crashName = sprintf('%04d%02d%02d%02d%02d%02d',year(t0),month(t0),day(t0),hour(t0),minute(t0),floor(second(t0)));
    
    % create and write to text file
    rootDir = getRootDir();
    crashDir = fullfile(rootDir,'crash_dumps');
    if ~isdir(crashDir)
        mkdir(crashDir)
    end
    crashFile = fullfile(crashDir,crashName);
    fID = fopen(crashFile, 'w');
    fprintf(fID,'%s',ME.getReport('extended','hyperlinks','off'));
    
    % close file
    fclose(fID);
end

%% getRootDir -------------------------------------------------------------
function rd = getRootDir()
% Returns CABLE root directory.
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% NOTE: turns out this is really hard to do in the compiled version. The
% only "easy" method that works assuredly is to use the Windows system
% command "path". So of course, it only works on Windows (and it seems
% MATLAB has issues with the Mac/Linux equivalent). Therefore, in attempt
% to make the code platform-independent, "pwd" is used for other platforms. 
% This works for me as long as CABLE is run from its directory... although
% someone did have inexplicable issues when I used "pwd" before.
%
% The hardcore solution would be to use a MEX file.

    if isdeployed % MATLAB Compiler function
        if ispc
            [~,sysPathStr] = system('path');
            rd = char(regexpi(sysPathStr,'Path=(.*?);','tokens','once'));
        else
            rd = pwd;
        end
    else
        rd = fileparts(fileparts(mfilename('fullpath')));
    end
end